    private void roundButton2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_roundButton2MouseClicked
        String username = value(roundTextField7, "Username");
        String phone = value(roundTextField9, "Phone");
        String email = value(roundTextField10, "Email");
        String password = value(roundTextField11, "Password");
        String confirm = value(roundTextField12, "Confirmed Password");

        if (username.isEmpty() || phone.isEmpty() || email.isEmpty()
                || password.isEmpty() || confirm.isEmpty()) {
            warn("กรุณากรอกข้อมูลให้ครบทุกช่อง");
            return;
        }
        if (username.contains(",") || phone.contains(",") || email.contains(",") || password.contains(",")) {
            warn("ห้ามใช้เครื่องหมายจุลภาค (,) ในข้อมูล");
            return;
        }
        if (!phone.matches("\\d{9,10}")) {
            warn("เบอร์โทรต้องเป็นตัวเลข 9-10 หลัก");
            return;
        }
        if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$")) {
            warn("รูปแบบ Email ไม่ถูกต้อง");
            return;
        }
        if (!password.equals(confirm)) {
            warn("Password และ Confirmed Password ไม่ตรงกัน");
            return;
        }
        if (UserDatabase.userExists(username)) {
            warn("Username นี้ถูกใช้งานแล้ว");
            return;
        }

        if (UserDatabase.saveUser(username, password, phone, email)) {
            javax.swing.JOptionPane.showMessageDialog(this, "สมัครสมาชิกสำเร็จ!", "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            goToLogin();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "ไม่สามารถบันทึกข้อมูลได้", "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_roundButton2MouseClicked

