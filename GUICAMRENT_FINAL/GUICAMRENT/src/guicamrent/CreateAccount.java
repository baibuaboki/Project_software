    /** ล้างข้อความตัวอย่างเมื่อคลิกช่อง และใส่กลับถ้าปล่อยว่าง */
    private void addPlaceholder(javax.swing.JTextField field, String placeholder) {
        field.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (field.getText().equals(placeholder)) {
                    field.setText("");
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (field.getText().trim().isEmpty()) {
                    field.setText(placeholder);
                }
            }
        });
    }

    /** ค่าในช่องที่ไม่ใช่ข้อความตัวอย่าง */
    private String value(javax.swing.JTextField field, String placeholder) {
        String t = field.getText().trim();
        return t.equals(placeholder) ? "" : t;
    }

